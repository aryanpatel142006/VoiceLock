def _ids(tracker):
    seen, prev = [], None
    for t, *box in BOXES:
        while prev is not None and t - prev > 0.3:  # the camera keeps sending frames with no face
            prev += 0.2
            tracker.update([], prev)
        prev = t
        for ft in tracker.update([Detection(tuple(box))], t):
            if not seen or seen[-1] != ft.track_id:
                seen.append(ft.track_id)
    return seen


def test_recorded_sequence_keeps_one_id_across_short_gaps():
    gaps = [b[0] - a[0] for a, b in pairwise(BOXES) if b[0] - a[0] > 0.3]
    assert sorted(round(g, 2) for g in gaps) == [1.04, 1.14, 1.38, 3.48, 6.76]
    ids = _ids(IouTracker())
    # one id per stretch between the long (> max_missing_s + reattach_s) gaps: 3, not 6
    assert len(ids) == 3, ids
    before = _ids(IouTracker(reattach_s=0.0))
    assert len(before) == 6, before  # what the session saw


def test_reattach_only_near_the_lost_face():
    tr = IouTracker(min_hits=1)
    first = tr.update([Detection((0.1, 0.4, 0.15, 0.25))], 0.0)[0].track_id
    assert tr.update([], 1.0) == []  # dropped after 0.7 s
    other = tr.update([Detection((0.7, 0.4, 0.15, 0.25))], 1.5)[0].track_id  # other side: new person
    assert other != first
    back = tr.update([Detection((0.7, 0.4, 0.15, 0.25)), Detection((0.11, 0.41, 0.15, 0.25))], 1.6)
    assert {ft.track_id for ft in back} == {first, other}


def test_reattach_window_expires():
    tr = IouTracker(min_hits=1, max_missing_s=0.7, reattach_s=2.0)
    first = tr.update([Detection((0.4, 0.4, 0.15, 0.25))], 0.0)[0].track_id
    tr.update([], 1.0)
    late = tr.update([Detection((0.4, 0.4, 0.15, 0.25))], 2.8)[0].track_id
    assert late != first


def test_reattach_s_validated():
    with pytest.raises(ValueError):
        IouTracker(reattach_s=-1.0)
